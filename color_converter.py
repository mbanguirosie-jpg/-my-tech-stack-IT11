def main():
    print("=== RGB → HEX КОНВЕРТЕР ===")
    print("Преобразование цветов RGB в шестнадцатеричный код")
    
    try:
        # Запросить значения RGB
        print("\nВведите значения RGB (от 0 до 255):")
        r = int(input("Красный (R) : "))
        g = int(input("Зеленый (G) : "))
        b = int(input("Синий (B) : "))
        
        # Проверьте, что значения верны.
        if not (0 <= r <= 255 and 0 <= g <= 255 and 0 <= b <= 255):
            print("\n Ошибка: значения должны быть в диапазоне от 0 до 255. !")
            return
        
        # Преобразовать в шестнадцатеричное число
        hex_code = f"#{r:02X}{g:02X}{b:02X}"
        
        # Показать результат
        print(f"\n Успешное преобразование !")
        print(f"   RGB({r}, {g}, {b}) = {hex_code}")
        
        # Специальный вариант 6
        if r == 255 and g == 128 and b == 0:
            print(f"\n Это цвет варианта 6.!")
            print("   #FF8000 = Ярко-оранжевый")
        
    except ValueError:
        print("\n Ошибка: введите допустимые целые числа. !")
    except Exception as e:
        print(f"\n Неожиданная ошибка : {e}")

# Основная точка входа
if __name__ == "__main__":
    main()
    print("\n" + "=" * 40)
    print("Программа завершена. СПАСИБО !")